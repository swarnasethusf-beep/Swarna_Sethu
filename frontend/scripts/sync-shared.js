/**
 * Copies the billing engine from the backend so the app's live preview uses
 * exactly the same maths as the server. Runs automatically before start/build.
 */
const fs = require("fs");
const path = require("path");

const src = path.join(__dirname, "..", "..", "backend", "lib", "billing.js");
const dest = path.join(__dirname, "..", "src", "shared", "billing.js");
const header = "/* GENERATED by scripts/sync-shared.js from backend/lib/billing.js — do not edit here. */\n";

if (!fs.existsSync(src)) {
  if (fs.existsSync(dest)) process.exit(0); // packaged without the backend folder: keep the committed copy
  console.error(`Cannot find ${src}`);
  process.exit(1);
}
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, header + fs.readFileSync(src, "utf8"));
console.log("✔ synced src/shared/billing.js");
